"""URI lookup tables for the batch-annotator (`_annotate_all_configs.py`).

Three tables:

- `NAME_URIS` — attribute / association-role local-name → compact-prefix URI.
  Applies uniformly across every mapping config. Extracted by parsing the
  first-line hint ('skos:X - ...') from each element's definition text.
  Auto-generated by scripts/_propose_uris.py (2026-07-07).

- `CLASS_URIS` — CDIF target-class name → compact-prefix URI.
  Same rules as NAME_URIS but at class scope.

- `PROFILE_OVERRIDES` — per-profile overrides for the ~22 names that map to
  different URIs in different profiles (e.g. `has` role is
  `cdif:has_CategoryStatistics` in DataDescription but
  `cdi:has_DataStructureComponent` in DataStructure). Keyed on
  (profile_slug, local_name) → URI. Beats NAME_URIS when a match is found.

- `PENDING_REVIEW` — names for which the automated extraction found no hint.
  Left as an empty-URI list so a human decides whether each has a source
  vocabulary or is CDIF-native (no URI needed).

Compact prefix keys the augmenter resolves:
  schema:  → http://schema.org/
  skos:    → http://www.w3.org/2004/02/skos/core#
  dcterms: → http://purl.org/dc/terms/
  dcat:    → http://www.w3.org/ns/dcat#
  prov:    → http://www.w3.org/ns/prov#
  dqv:     → http://www.w3.org/ns/dqv#
  spdx:    → http://spdx.org/rdf/terms#
  time:    → http://www.w3.org/2006/time#
  geo:     → http://www.opengis.net/ont/geosparql#
  cdi:     → http://ddialliance.org/Specification/DDI-CDI/1.0/RDF/
  cdif:    → https://w3id.org/cdif/    (CDIF-modified cdi terms)

Names bound to `cdif:X` are CDIF-modified `cdi:X` terms — the augmenter
uses the source `cdi:X` property as the upstream source in the Original
section (Reference still shows the `cdif:X` URI so consumers see the
CDIF-specific namespace; Definition/Scope come from the DDI-CDI source).
"""

