def resolve_uri(profile: str, class_name: str, attr_name: str) -> str:
    """Return the best-matching source URI for a given (profile, class, attr).

    Lookup order (first hit wins):
      1. 3-tuple: PROFILE_OVERRIDES[(profile, class_name, attr_name)]
      2. 2-tuple: PROFILE_OVERRIDES[(profile, attr_name)]
      3. Flat NAME_URIS[attr_name]
      4. PENDING_REVIEW[attr_name]
      5. CDI_CLASS_ATTRS[class_name] contains attr_name → `cdi:<Class>-<attr>`
      6. Empty string (leave the sourceUri field blank).

    The batch annotator (`_annotate_all_configs.py`) uses this to write the
    `sourceUri:` field into each mapping-config element."""
    triple = PROFILE_OVERRIDES.get((profile, class_name, attr_name))
    if triple:
        return triple
    pair = PROFILE_OVERRIDES.get((profile, attr_name))
    if pair:
        return pair
    if attr_name in NAME_URIS:
        return NAME_URIS[attr_name]
    if attr_name in PENDING_REVIEW:
        return PENDING_REVIEW[attr_name]
    if attr_name in CDI_CLASS_ATTRS.get(class_name, ()):
        return f"cdi:{class_name}-{attr_name}"
    return ""


def resolve_class_uri(class_name: str) -> str:
    """Return the CLASS_URIS entry for a target class, or empty string if
    none. `None` values (CDIF-invented classes with no upstream source) are
    returned as-is so callers can distinguish "explicit no-source" from
    "unknown"."""
    val = CLASS_URIS.get(class_name)
    return val if val is not None else ""


